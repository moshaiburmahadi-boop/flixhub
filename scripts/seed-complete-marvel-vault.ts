async function seedCompleteMarvelVault() {
  console.log('Fetching existing movies from Firestore to avoid duplicates...');
  const snapshot = await getDocs(collection(db, 'movies'));
  const existingTitles = new Set<string>();
  snapshot.forEach((doc) => {
    const data = doc.data();
    if (data.title) {
      existingTitles.add(data.title.trim().toLowerCase());
    }
  });

  console.log(`Found ${existingTitles.size} existing titles in Firestore.`);

  // Filter out any duplicates
  const toAdd = MASTER_MARVEL_LIST.filter(
    (item) => !existingTitles.has(item.title.trim().toLowerCase())
  );

  console.log(`${toAdd.length} new Marvel titles to add out of ${MASTER_MARVEL_LIST.length}.`);

  // Batch insert into Firestore in chunks of 20
  const chunkSize = 20;
  for (let i = 0; i < toAdd.length; i += chunkSize) {
    const chunk = toAdd.slice(i, i + chunkSize);
    const batch = writeBatch(db);

    for (const movie of chunk) {
      const slug = movie.title
        .toLowerCase()
        .replace(/[^a-z0-9]/g, '_')
        .replace(/_+/g, '_')
        .substring(0, 40);
      const docId = `marvel_${slug}_${movie.releaseYear}`;
      const docRef = doc(db, 'movies', docId);

      const movieDoc: MovieItem = {
        ...movie,
        id: docId,
        createdAt: new Date(Date.now() - (toAdd.length - i) * 1000 * 60 * 60 * 12).toISOString(),
        updatedAt: new Date().toISOString(),
      };

      batch.set(docRef, movieDoc, { merge: true });
    }

    await batch.commit();
    console.log(`Committed chunk ${Math.floor(i / chunkSize) + 1} (${chunk.length} items)...`);
  }

  // Update Marvel Category subcategories to include all universes
  const marvelCategoryRef = doc(db, 'categories', 'cat_marvel_mcu');
  await setDoc(
    marvelCategoryRef,
    {
      id: 'cat_marvel_mcu',
      name: 'Marvel',
      subCategories: [
        'Avengers',
        'Spider-Man',
        'X-Men',
        'Venom',
        'Defenders',
        'Iron Man',
        'Guardians',
        'Fantastic Four',
        'Disney+ Series',
        'Classics',
        'Phase 1-3',
        'Latest Phase 4 & 5',
      ],
      createdAt: new Date().toISOString(),
    },
    { merge: true }
  );

  console.log('Marvel category updated with comprehensive subcategory tags.');
  console.log('All Marvel movies and series seeded successfully with ZERO duplicates!');
  process.exit(0);
}

seedCompleteMarvelVault().catch((err) => {
  console.error('Error seeding complete marvel vault:', err);
  process.exit(1);
});
